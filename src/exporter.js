// Bộ xuất file 3D OBJ chuẩn để mở trong Blender, Paint 3D, Windows 3D Viewer
export function exportToOBJ(mesh, filename = 'technical_model.obj') {
  if (!mesh || !mesh.geometry) return;
  const geom = mesh.geometry.clone().toNonIndexed();
  const pos = geom.attributes.position;
  const norm = geom.attributes.normal;

  let objOutput = '# Technical 3D Block Model\n# Generated by Isometric 3D CAD Builder\no Model\n\n';

  // Vertices
  for (let i = 0; i < pos.count; i++) {
    objOutput += `v ${pos.getX(i).toFixed(4)} ${pos.getY(i).toFixed(4)} ${pos.getZ(i).toFixed(4)}\n`;
  }

  // Normals
  if (norm) {
    objOutput += '\n';
    for (let i = 0; i < norm.count; i++) {
      objOutput += `vn ${norm.getX(i).toFixed(4)} ${norm.getY(i).toFixed(4)} ${norm.getZ(i).toFixed(4)}\n`;
    }
  }

  // Faces
  objOutput += '\ns 1\n';
  for (let i = 0; i < pos.count; i += 3) {
    const v1 = i + 1, v2 = i + 2, v3 = i + 3;
    if (norm) {
      objOutput += `f ${v1}//${v1} ${v2}//${v2} ${v3}//${v3}\n`;
    } else {
      objOutput += `f ${v1} ${v2} ${v3}\n`;
    }
  }

  const blob = new Blob([objOutput], { type: 'text/plain;charset=utf-8' });
  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.download = filename;
  link.click();
  URL.revokeObjectURL(link.href);
}
